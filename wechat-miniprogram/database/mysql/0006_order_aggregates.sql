CREATE TABLE IF NOT EXISTS `order_aggregates` (
  `id` VARCHAR(64) NOT NULL,
  `buyer_id` VARCHAR(64) NOT NULL,
  `provider_id` VARCHAR(64) NOT NULL,
  `request_idempotency_key` VARCHAR(128) NOT NULL,
  `request_hash` CHAR(64) NOT NULL,
  `stage` VARCHAR(32) NOT NULL DEFAULT 'REQUESTED',
  `payload` JSON NOT NULL,
  `version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_at` BIGINT UNSIGNED NOT NULL,
  `updated_at` BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `order_aggregates_buyer_idempotency_unique` (`buyer_id`, `request_idempotency_key`),
  KEY `order_aggregates_buyer_stage_idx` (`buyer_id`, `stage`, `updated_at`),
  KEY `order_aggregates_provider_stage_idx` (`provider_id`, `stage`, `updated_at`),
  CONSTRAINT `order_aggregates_buyer_fk` FOREIGN KEY (`buyer_id`) REFERENCES `accounts` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `order_aggregates_provider_fk` FOREIGN KEY (`provider_id`) REFERENCES `accounts` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `order_aggregates_stage_check` CHECK (`stage` IN ('REQUESTED','SUPPLEMENT_REQUESTED','SUPPLEMENTED','CONTACTING','NDA_BUYER_PENDING','NDA_PROVIDER_PENDING','BUYER_FINAL_CONFIRM','IN_PRODUCTION','REVISION_REQUESTED','DELIVERY_PENDING','COMPLETED','DECLINED')),
  CONSTRAINT `order_aggregates_version_check` CHECK (`version` >= 1),
  CONSTRAINT `order_aggregates_time_check` CHECK (`updated_at` >= `created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
