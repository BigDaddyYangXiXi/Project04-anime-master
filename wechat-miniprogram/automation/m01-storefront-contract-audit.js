const assert = require("assert");
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "../miniprogram");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const meWxml = read("pages/me/index.wxml");
const meJs = read("pages/me/index.js");
const meWxss = read("pages/me/index.wxss");
const profileWxml = read("pages/provider-profile/index.wxml");
const profileJs = read("pages/provider-profile/index.js");
const providerDetailWxml = read("pages/provider-detail/index.wxml");
const providerDetailJs = read("pages/provider-detail/index.js");
const fundsJs = read("pages/funds/index.js");
const workJs = read("pages/work-detail/index.js");
const storeJs = read("data/v063-store.js");
const appJson = JSON.parse(read("app.json"));
const buyerBlock = meWxml.slice(meWxml.indexOf('<block wx:else>'), meWxml.indexOf('<view class="section-card asset-card">'));

assert.ok(meWxml.includes("show-role-switch") && meWxml.includes("bindroleswitch=\"switchIdentity\""), "M01 必须只保留左上角身份切换入口");
assert.ok(meWxml.includes("上传作品") && meWxml.includes("编辑橱窗") && meWxml.includes("资金管理"), "服务方三个一级经营入口缺失");
assert.ok(meWxml.includes('class="profile-card"') && meWxml.includes('class="profile-business"'), "经营数据必须与头像身份合并为同一卡片组件");
assert.ok(meWxml.includes('src="{{account.avatar}}"') && meWxml.includes("avatar-fallback") && !meWxml.includes("slime-eye"), "身份卡使用真实头像及缺省身份，不强制品牌装饰");
assert.ok(meWxml.includes(">橱窗预览<") && !meWxml.includes("以需求方视角预览"), "M01 预览入口必须简称为橱窗预览");
assert.ok(profileWxml.includes("保存草稿，下一步") && profileWxml.includes("返回橱窗") && profileWxml.includes("保存作品草稿"), "橱窗及作品保存必须明确是草稿");
assert.ok(profileJs.includes("saveAndPreview()") && profileJs.includes("preview=storefront"), "保存橱窗后必须进入待确认的服务方预览");
assert.ok(providerDetailWxml.includes("确认并公开发布") && providerDetailWxml.includes("storefrontDraftPreview && !visitorDraftPreview") && providerDetailWxml.includes("!providerPreview || visitorDraftPreview"), "发布预览专用确认区与普通/访客预约区必须区分");
assert.ok(providerDetailJs.includes("confirmPublish()") && providerDetailJs.includes("storefrontPreviewDraft.markPublished()"), "只有预览确认后才能写入正式橱窗");
assert.ok(!profileWxml.includes("summary-card") && !profileWxml.includes("编辑公开资料、服务与作品") && profileJs.includes("openEditor()"), "S02 不得保留独立服务橱窗展示中转页");
assert.ok(/\.primary-actions\s*\{[^}]*grid-template-columns:\s*repeat\(2,minmax\(0,1fr\)\)/s.test(meWxss), "编辑橱窗与上传作品必须使用等宽双列网格");
assert.ok(!meWxml.includes("funds-action") && meWxml.indexOf('class="funds-entry"') < meWxml.indexOf('class="hero-card"'), "资金管理必须位于经营数据下方，不得留在经营中心操作网格");
assert.ok(/\.main-action\s*\{[^}]*align-items:\s*center/s.test(meWxss) && meWxss.includes("var(--am-touch-min)"), "经营入口须成组对齐并使用共用触控尺寸");
assert.ok(meWxml.includes('class="main-action work-action"') && !meWxml.includes("selected-action"), "经营入口为动作，不伪装成已选中选项");
assert.ok(!/#f38a8e|#e96e82/.test(meWxss) && meWxss.includes("var(--am-color-brand)"), "经营入口沿用现行品牌token，不回退旧珊瑚渐变");
assert.ok(buyerBlock.includes('class="hero-card buyer-hero"') && buyerBlock.includes('class="primary-actions"'), "供需常用功能必须复用双列入口骨架");
assert.ok(buyerBlock.includes("查看订单") && buyerBlock.includes("我的项目"), "需求方必须保留订单与项目入口");
assert.ok(!buyerBlock.includes("编辑橱窗") && !buyerBlock.includes("上传作品") && !buyerBlock.includes("资金管理") && !buyerBlock.includes("橱窗预览"), "需求方不得出现服务方专属能力");
assert.ok(meWxml.includes("role === 'provider' ? 'provider-stats' : 'buyer-stats'") && meWxml.includes("role === 'provider' ? providerStats : buyerStats"), "供需经营／合作数据必须并入同一身份卡组件");
assert.ok(meWxml.includes('wx:if="{{role === \'provider\'}}" class="funds-entry"'), "资金管理只能向服务方显示");
assert.ok(/\.preview-button\s*\{[^}]*border:\s*2rpx solid var\(--am-color-border\)/s.test(meWxss), "橱窗预览必须使用规范描边按钮");
assert.ok(meJs.includes("section=works") && meJs.includes("section=profile") && meJs.includes("provider-detail/index"), "编辑入口与需求方预览路由必须写死对应");
assert.ok(meJs.includes("if (!this.auditMode) { this.loadCloudDashboard(role)") && meJs.includes("cloudOrders.listOrders()") && meJs.includes("cloudSavedItems.listMine()"), "真实经营指标从云端读取，本地示例限制于审查分支");
assert.ok(!meJs.includes("providers") && !meJs.includes("store.getWorks()"), "M01 不得从本地演示目录或本地作品数组临时拼装经营数据");
assert.ok(meJs.includes("cloudCatalog.getProvider(account.id)") && meJs.includes("referenceCount"), "M01 作品与参考统计必须读取本人云端公开橱窗聚合");
assert.ok(storeJs.includes('meDashboard: "anime-master-v063-me-dashboard"') && storeJs.includes("function getMeDashboard(role)"), "数据层必须提供明确的 M01 后端快照契约");
assert.ok(meWxml.includes("{{previewMeta}}") && !meWxml.includes("worksCount"), "橱窗预览数量不得直接使用作品数组长度");
assert.ok(profileWxml.includes("editorSection !== 'works'") && profileWxml.includes("editorSection === 'works'"), "作品与橱窗编辑必须是两个明确分区");
assert.ok(profileWxml.includes("previewSelectedWork") && profileJs.includes("/pages/work-detail/index"), "作品编辑必须提供需求方详情预览");
assert.ok(workJs.includes("anime-master-v063-liked-work-ids"), "我的喜欢必须来自可写入的作品行为状态");
assert.ok(fundsJs.includes("cloudOrders.getProviderFunds") && !fundsJs.includes("v063-store"), "资金记录必须由当前服务方的云端付款事实提供");
assert.ok(fundsJs.includes("不代表已结算") && !fundsJs.includes("withdrawSuccess"), "付款不得冒充已结算或模拟提现成功");
["pages/account-profile/index", "pages/me-assets/index", "pages/funds/index"].forEach((route) => assert.ok(appJson.pages.includes(route), `${route} 未注册`));
process.stdout.write("M01 storefront contract audit passed\n");
