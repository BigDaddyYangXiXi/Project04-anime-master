assert.match(page, /cloudAccount\.getMine/);
assert.match(page, /cloudAccount\.updateMine/);
assert.match(page, /accountVersion/);
assert.match(page, /VERSION_CONFLICT/);
assert.match(page, /uploadImage\(file, "AVATAR"\)/);
assert.match(page, /getImageStatus/);
assert.match(page, /cancelImage/);
assert.doesNotMatch(page, /store\.saveAccount[\s\S]*cloudMode[\s\S]*store\.saveAccount/);
