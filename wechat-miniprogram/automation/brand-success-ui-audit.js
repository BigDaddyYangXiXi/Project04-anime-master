const assert = require("assert");
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..", "miniprogram");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const component = read("components/brand-success-card/index.wxml");
const componentStyle = read("components/brand-success-card/index.wxss");
const fulfillment = read("pages/fulfillment/index.wxml");
const review = read("pages/review/index.wxml");
const detail = read("pages/order-detail/index.wxml");
const asset = path.join(root, "assets", "brand", "peach-slime-main-768.jpg");
assert.ok(fs.existsSync(asset) && fs.statSync(asset).size < 100000, "正式史莱姆资产必须存在且适合小程序体积");
assert.ok(component.includes("peach-slime-main-768.jpg") && component.includes('mode="aspectFill"'), "成功组件必须使用正式主形象母版");
for (const wxml of [fulfillment, review, detail]) assert.ok(wxml.includes("brand-success-card"), "完成与评价页面必须复用主形象成功组件");
assert.ok(review.includes("review-brand-hero") && review.includes("providerIdentity.nickname") && review.includes("providerIdentity.uid"), "评价表单必须保留主形象和服务方昵称 UID");
const affectedStyles = [read("pages/fulfillment/index.wxss"), read("pages/review/index.wxss")].join("\n");
assert.ok(!affectedStyles.includes("slime-mark"), "不得保留薄荷色 CSS 临时史莱姆");
assert.ok(!componentStyle.includes("box-shadow:") || componentStyle.includes("box-shadow: none"), "主形象组件不得添加装饰阴影");
process.stdout.write("Brand slime success and review UI audit: 9 assertions passed\n");
