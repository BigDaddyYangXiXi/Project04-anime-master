const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const page = read("miniprogram/pages/funds/index.js");
const wxml = read("miniprogram/pages/funds/index.wxml");
const core = read("cloudfunctions/order-api/funds-core.js");
assert.ok(!page.includes("v063-store"), "资金页不读本地演示数据");
assert.ok(page.includes("cloudOrders.getProviderFunds"), "资金页必须调用真实权限接口");
assert.ok(core.includes('order_aggregates!inner(provider_id)') && core.includes('actor.accountId'), "支付记录按订单归属限定本人");
assert.ok(core.includes('withdrawableBalanceFen: null'), "未接通结算不得伪造零余额");
assert.ok(!wxml.includes('正在读取'), '普通读取不显示过程提示');
for (const label of ["资金记录未能加载", "暂无已确认的付款记录", "加载更多", "重试加载更多", "提现指南", "预计收益"]) assert.ok(wxml.includes(label), label);
assert.ok(wxml.includes('bindtap="openOrder"') && page.includes("/pages/provider-request/index"), "整行进入既有服务方订单");
for (const key of ["withdraw", "recharge", "password"]) assert.ok(!wxml.includes('data-key="' + key + '"'), "移除未接入的资金按钮");
assert.ok(wxml.includes("结算状态") && wxml.includes("待开通"), "结算未知状态应明确显示");
assert.ok(JSON.parse(read("miniprogram/pages/funds/index.json")).enablePullDownRefresh, "资金页支持下拉刷新");
process.stdout.write("Funds cloud-record contract audit passed\n");
